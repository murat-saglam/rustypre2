//! Read-only DGROUP lookup table accessors (`ByteTable`, `WordTable`, and `Tables`).

use crate::engine::state::NativeGameState;

/// Read-only byte table at a fixed DGROUP base offset.
pub struct ByteTable;

impl ByteTable {
    /// Read the byte at `(base + i) & 0xFFFF` in `DGROUP`.
    #[inline]
    pub fn read(state: &NativeGameState, base: usize, i: usize) -> u8 {
        state.rb((base + i) & 0xFFFF)
    }
}

/// Immutable static byte table asset.
pub struct NativeByteTable {
    data: &'static [u8],
}

impl NativeByteTable {
    pub const fn new(data: &'static [u8]) -> Self {
        Self { data }
    }

    /// Return the byte at index `i`, panicking if out of range.
    #[inline]
    pub fn get(&self, i: usize) -> u8 {
        self.data[i]
    }
}

/// Read-only 16-bit word table at a fixed DGROUP base offset.
pub struct WordTable;

impl WordTable {
    /// Read the 16-bit word at `(base + i) & 0xFFFF` in `DGROUP`.
    #[inline]
    pub fn read(state: &NativeGameState, base: usize, i: usize) -> u16 {
        state.rw((base + i) & 0xFFFF)
    }
}

